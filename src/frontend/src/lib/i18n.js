/** @returns {Locale} */
function initialLocale() {
  if (typeof localStorage !== "undefined") {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (isLocale(stored)) return /** @type {Locale} */ (stored);
  }
  if (typeof navigator !== "undefined") {
    const language = navigator.language?.toLowerCase() || "";
    if (language.startsWith("en")) return "en";
  }
  return DEFAULT_LOCALE;
}

/** @param {unknown} value */
export function isLocale(value) {
  return typeof value === "string" && LOCALES.includes(/** @type {Locale} */ (value));
}

/** @type {import("svelte/store").Writable<Locale>} */
export const locale = writable(initialLocale());

/** @param {string} code */
export function setLocale(code) {
  const next = isLocale(code) ? /** @type {Locale} */ (code) : DEFAULT_LOCALE;
  if (typeof localStorage !== "undefined") {
    localStorage.setItem(STORAGE_KEY, next);
  }
  locale.set(next);
}

